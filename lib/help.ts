/* The help assistant (spec §7, /api/claude with kind "help"). It is public, so the server builds its
   prompt with the page's own builder (site/help/help-prompt.js, compiled into lib/generated by the build)
   from the help topics and this deployment's GOV.UK text. Whatever system prompt the page sends is ignored. */
import { cleanClaudeRequest, type ClaudeMessage, type ClaudeRequest } from './claude.js'
import { HELP_SOURCES, HELPPROMPT } from './generated/help-prompt.js'
import { createLimiter } from './ratelimit.js'

export const HELP_MAX_TOKENS = 700

export interface HelpContent {
  built?: string | null
  pages?: Record<string, unknown>
  forms?: unknown[]
}

interface HelpPrompt {
  build(sources: unknown, content: HelpContent, messages: ClaudeMessage[]): string
  trim(messages: ClaudeMessage[]): ClaudeMessage[]
  LIMIT: { system: number; turns: number }
}

const P = HELPPROMPT as HelpPrompt | null

/** whether this build carries the help assistant's prompt builder */
export const helpReady = (): boolean => !!(P && typeof P.build === 'function' && typeof P.trim === 'function' && HELP_SOURCES)

/* The request, cleaned: the page's messages trimmed by the page's own rules, the conversation starting
   and ending with the person, at most 700 tokens, and the system prompt the server's own */
export function cleanHelpRequest(body: unknown, content: HelpContent): { ok: true; request: ClaudeRequest } | { ok: false; error: string } {
  if (!P || !helpReady()) return { ok: false, error: 'The help assistant is not in this build.' }
  const b = body && typeof body === 'object' && !Array.isArray(body) ? (body as Record<string, unknown>) : null
  if (!b) return { ok: false, error: 'Expected an object.' }
  /* the last turns the page's builder keeps, from the person's first one */
  let recent: unknown = b.messages
  if (Array.isArray(recent)) {
    const list = recent.slice(-(P.LIMIT.turns || 8))
    while (list.length > 1 && (list[0] as { role?: unknown } | null)?.role === 'assistant') list.shift()
    recent = list
  }
  const cleaned = cleanClaudeRequest({ messages: recent, max_tokens: b.max_tokens })
  if (!cleaned.ok) return cleaned
  const messages = P.trim(cleaned.request.messages)
  const system = P.build(HELP_SOURCES, content, messages)
  return { ok: true, request: { system, messages, max_tokens: Math.min(cleaned.request.max_tokens, HELP_MAX_TOKENS) } }
}

/* This deployment's help/help-content.json, read once per instance. When it can't be read (a preview
   behind Vercel's login, say) the live site's copy stands in, and failing that no GOV.UK text: the
   prompt then points to the GOV.UK pages by topic and gives no figures. */
let content: { at: number; value: HelpContent; from: 'own' | 'live' | 'none' } | null = null
const RETRY_MS = 5 * 60 * 1000

export async function helpContent(origin: string, live: string, now: number = Date.now()): Promise<{ value: HelpContent; from: 'own' | 'live' | 'none' }> {
  if (content && (content.from === 'own' || now - content.at < RETRY_MS)) return content
  const get = async (base: string): Promise<HelpContent | null> => {
    try {
      const res = await fetch(new URL('/help/help-content.json', base), { signal: AbortSignal.timeout(3000) })
      if (!res.ok) return null
      const j = (await res.json()) as HelpContent
      return j && typeof j === 'object' && j.pages && typeof j.pages === 'object' ? j : null
    } catch {
      return null
    }
  }
  const own = await get(origin)
  if (own) content = { at: now, value: own, from: 'own' }
  else {
    const fromLive = live && new URL(live).origin !== new URL(origin).origin ? await get(live) : null
    content = fromLive ? { at: now, value: fromLive, from: 'live' } : { at: now, value: { built: null, pages: {}, forms: [] }, from: 'none' }
  }
  return content
}

/** tests start each case with nothing kept */
export function clearHelpContent(): void {
  content = null
}

/* Limits for visitors who passed the person check (spec §7): 15 an hour and 40 a day per session, and
   300 an hour across everyone. Per instance, like the other limits. A refused call uses up nothing. */
export const helpHourLimiter = createLimiter(15, 60 * 60 * 1000)
export const helpDayLimiter = createLimiter(40, 24 * 60 * 60 * 1000)
export const helpAllLimiter = createLimiter(300, 60 * 60 * 1000)

export function helpVisitorAllowed(key: string, now: number = Date.now()): boolean {
  if (!helpDayLimiter.allows(key, now) || !helpHourLimiter.allows(key, now) || !helpAllLimiter.allows('all', now)) return false
  helpDayLimiter.hit(key, now)
  helpHourLimiter.hit(key, now)
  helpAllLimiter.hit('all', now)
  return true
}

export function resetHelpLimits(): void {
  helpHourLimiter.reset()
  helpDayLimiter.reset()
  helpAllLimiter.reset()
}
